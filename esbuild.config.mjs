import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/** esbuild writes imported CSS to main.css; Obsidian expects styles.css. */
const renameCssPlugin = {
  name: "rename-css",
  setup(build) {
    build.onEnd(() => {
      if (fs.existsSync("main.css")) {
        fs.renameSync("main.css", "styles.css");
      }
    });
  },
};

const EXCALIDRAW_DIR = "node_modules/@excalidraw/excalidraw";

/**
 * Size control:
 * - `mermaid` (+ cytoscape chain, ~2.7MB) is stubbed out. The "insert →
 *   mermaid diagram" feature is out of scope for v0.1; everything else in the
 *   package does not depend on it at runtime.
 * - Locale chunks other than en-GB / zh-CN (~1.6MB) are stubbed with {}.
 * - Font files referenced as "./fonts/…" strings are inlined as data URLs at
 *   build time, except the 12MB Xiaolai CJK subsets (system font fallback
 *   covers CJK glyphs; Xiaolai would load from the esm.sh fallback URL only
 *   if ever selected).
 */
const slimExcalidrawPlugin = {
  name: "slim-excalidraw",
  setup(build) {
    const stubNamespace = "slim-stub";
    build.onResolve({ filter: /^mermaid$/ }, (args) => ({
      path: "mermaid-stub",
      namespace: stubNamespace,
    }));
    build.onLoad({ filter: /.*/, namespace: stubNamespace }, () => ({
      contents: `const noop = new Proxy(function noop() {}, {
        get: () => noop,
        apply: () => noop,
      });
      export default noop;
      export const mermaid = noop;`,
      loader: "js",
    }));

    build.onResolve(
      { filter: /\/locales\/[a-zA-Z]{2}(?:-[A-Za-z0-9]{2,8})?-[^/]*\.js$/ },
      (args) => {
        const base = path.basename(args.path);
        if (base.startsWith("en-GB") || base.startsWith("zh-CN")) {
          return null;
        }
        return { path: "locale-stub", namespace: stubNamespace };
      },
    );
    build.onLoad(
      { filter: /^locale-stub$/, namespace: stubNamespace },
      () => ({ contents: "export default {};", loader: "js" }),
    );

    build.onLoad(
      { filter: /@excalidraw[\\/]excalidraw[\\/]dist[\\/]prod[\\/].*\.js$/ },
      (args) => {
        const src = fs.readFileSync(args.path, "utf8");
        if (!src.includes("./fonts/")) {
          return null;
        }
        const contents = src.replace(
          /(["'])\.\/fonts\/(?!Xiaolai)([A-Za-z]+)\/([A-Za-z0-9._-]+\.woff2)\1/g,
          (whole, quote, family, file) => {
            const fontPath = path.join(
              EXCALIDRAW_DIR,
              "dist/prod/fonts",
              family,
              file,
            );
            if (!fs.existsSync(fontPath)) {
              return whole;
            }
            const b64 = fs.readFileSync(fontPath).toString("base64");
            return `${quote}data:font/woff2;base64,${b64}${quote}`;
          },
        );
        return { contents, loader: "js" };
      },
    );
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
  plugins: [renameCssPlugin, slimExcalidrawPlugin],
  conditions: ["production", "default"],
  loader: {
    ".woff2": "dataurl",
    ".woff": "dataurl",
    ".ttf": "dataurl",
    ".png": "dataurl",
    ".jpg": "dataurl",
    ".svg": "dataurl",
  },
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
